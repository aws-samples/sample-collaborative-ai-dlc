import { useEffect, useMemo, useState } from 'react';
import { api } from '@/services/api';
import type { Intent, ProjectMetrics } from '@/services/intents';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader } from '@/components/ui/card';
import { ErrorState } from '@/components/ui/empty-state';
import { MetricRow, Stat } from '@/components/ui/stat';
import { RelativeTime } from '@/components/ui/relative-time';
import { useQuery } from '@tanstack/react-query';
import { qk } from '@/lib/queryKeys';
import { formatCost, formatTokens } from '@/lib/metricAggregation';
import { formatCount } from '@/lib/format';

const USAGE_STALE_MS = 5 * 60_000;
const COMPLETED_WINDOW_DAYS = 30;
const API_INTENT_CAP = 100;
const SLOW_LOAD_AFTER_S = 8;

// The per-run usage read is slow (one PRISM read per intent), so it only runs
// when asked for; a fresh cached answer is shown without asking again.
function useSpaceMetrics(projectId: string) {
  const [requested, setRequested] = useState(false);
  const query = useQuery({
    queryKey: qk.spaceMetrics(projectId, 'all'),
    queryFn: ({ signal }) =>
      api.get<ProjectMetrics>(`/projects/${projectId}/intents/metrics`, { signal }),
    staleTime: USAGE_STALE_MS,
    enabled: requested,
  });
  return {
    data: query.data,
    error: query.error,
    isFetching: query.isFetching,
    available:
      requested || (query.data !== undefined && Date.now() - query.dataUpdatedAt < USAGE_STALE_MS),
    load: () => setRequested(true),
    retry: () => query.refetch(),
  };
}

function useElapsedSeconds(active: boolean): number {
  const [seconds, setSeconds] = useState(0);
  useEffect(() => {
    if (!active) return;
    setSeconds(0);
    const timer = setInterval(() => setSeconds((value) => value + 1), 1_000);
    return () => clearInterval(timer);
  }, [active]);
  return active ? seconds : 0;
}

const positive = (value: number | undefined | null): number | null =>
  typeof value === 'number' && Number.isFinite(value) && value > 0 ? value : null;

function UsageStats({ data }: { data: ProjectMetrics }) {
  const metrics = data.project?.metrics ?? null;
  const cost = data.project?.cost ?? null;
  const tokensIn = positive(metrics?.tokensInput);
  const tokensOut = positive(metrics?.tokensOutput);
  const totalCost = positive(cost?.totalCost);
  const summaryMissing = metrics === null && cost === null;
  if (
    !summaryMissing &&
    tokensIn === null &&
    tokensOut === null &&
    totalCost === null &&
    !cost?.anyUnpriced
  ) {
    return <p className="text-xs text-muted-foreground">No usage recorded for this space yet.</p>;
  }

  return (
    <div className="space-y-2">
      <p className="text-xs font-medium text-muted-foreground">Recorded usage · all dates</p>
      <MetricRow aria-label="Usage and cost">
        {summaryMissing || tokensIn !== null ? (
          <Stat
            label="Input tokens"
            value={tokensIn === null ? null : formatTokens(tokensIn)}
            state={tokensIn === null ? 'missing' : 'ok'}
            hint="Sent to the models across every run in this space."
          />
        ) : null}
        {summaryMissing || tokensOut !== null ? (
          <Stat
            label="Output tokens"
            value={tokensOut === null ? null : formatTokens(tokensOut)}
            state={tokensOut === null ? 'missing' : 'ok'}
            hint="Generated by the models."
          />
        ) : null}
        <Stat
          label="Cost"
          value={cost && totalCost !== null ? formatCost(totalCost, cost.currency) : null}
          state={
            !cost || cost.anyUnpriced || totalCost === null
              ? 'missing'
              : cost.anyEstimated
                ? 'estimated'
                : 'ok'
          }
          hint={
            !cost
              ? 'No cost summary was returned for this space.'
              : cost.anyUnpriced
                ? 'Some runs used a model without a known price.'
                : cost.anyEstimated
                  ? 'Includes credit-based estimates.'
                  : 'Priced from recorded token usage.'
          }
        />
      </MetricRow>
    </div>
  );
}

function UsagePanel({ projectId }: { projectId: string }) {
  const { data, error, isFetching, available, load, retry } = useSpaceMetrics(projectId);
  const loading = available && !data && isFetching;
  const elapsed = useElapsedSeconds(loading);

  if (!available) {
    return (
      <div className="flex flex-wrap items-center gap-x-3 gap-y-1">
        <Button type="button" variant="outline" size="sm" onClick={() => load()}>
          Load usage
        </Button>
        <span className="text-xs text-muted-foreground">Can take up to a minute.</span>
      </div>
    );
  }
  if (loading) {
    return (
      <p role="status" aria-label="Loading usage" className="text-xs text-muted-foreground">
        <span className="tabular-nums">Reading usage for every run… {elapsed} s</span>
        {elapsed >= SLOW_LOAD_AFTER_S ? (
          <span className="block">
            Metrics are read run by run, which can take up to a minute on large spaces.
          </span>
        ) : null}
      </p>
    );
  }
  if (!data) {
    return (
      <ErrorState
        size="section"
        title="Couldn't load usage and cost"
        description={
          error instanceof Error && error.message
            ? error.message
            : 'The usage summary could not be retrieved.'
        }
        onRetry={retry}
        retrying={isFetching}
      />
    );
  }
  return <UsageStats data={data} />;
}

function completedWithin(intents: readonly Intent[], now: number) {
  const cutoff = now - COMPLETED_WINDOW_DAYS * 86_400_000;
  let count = 0;
  let undated = 0;
  let latest: string | null = null;
  let latestMs = -Infinity;
  for (const intent of intents) {
    if (intent.status !== 'SUCCEEDED') continue;
    const completedAt = intent.completedAt ? Date.parse(intent.completedAt) : NaN;
    if (!Number.isFinite(completedAt)) {
      undated += 1;
      continue;
    }
    if (completedAt > latestMs) {
      latestMs = completedAt;
      latest = intent.completedAt;
    }
    if (completedAt >= cutoff && completedAt <= now) count += 1;
  }
  return { count, undated, latest };
}

export interface SpaceActivityCostProps {
  projectId: string;
  intents: readonly Intent[];
  /** Owners see token usage and cost; members only the completion count. */
  canSeeCost: boolean;
  now?: number;
}

export function SpaceActivityCost({
  projectId,
  intents,
  canSeeCost,
  now = Date.now(),
}: SpaceActivityCostProps) {
  const completed = useMemo(() => completedWithin(intents, now), [intents, now]);
  const capped = intents.length >= API_INTENT_CAP;
  const partial = capped || completed.undated > 0;
  const label = `Completed in the last ${COMPLETED_WINDOW_DAYS} days`;
  const partialHint = capped
    ? `Based on the first ${intents.length} intents returned by the space.`
    : `A completion date is missing for ${completed.undated} finished ${completed.undated === 1 ? 'intent' : 'intents'}.`;

  const completedStat =
    completed.count > 0 ? (
      <Stat
        label={label}
        value={<span data-testid="space-activity-count">{formatCount(completed.count)}</span>}
        hint={partial ? partialHint : undefined}
      />
    ) : partial ? (
      <Stat label={label} value={null} state="missing" hint={partialHint} />
    ) : (
      <Stat
        label={label}
        value={
          <span data-testid="space-activity-count" className="font-normal text-muted-foreground">
            None
          </span>
        }
      />
    );

  return (
    <section aria-labelledby="space-activity-heading">
      <Card>
        <CardHeader className="pb-3">
          <h2 id="space-activity-heading" className="text-sm font-semibold leading-none">
            {canSeeCost ? 'Activity & cost' : 'Activity'}
          </h2>
        </CardHeader>
        <CardContent className="space-y-4">
          <MetricRow aria-label="Space activity">
            {completedStat}
            <Stat
              label="Last completion"
              value={
                completed.latest ? (
                  <RelativeTime value={completed.latest} now={now} />
                ) : (
                  <span className="font-normal text-muted-foreground">None yet</span>
                )
              }
            />
          </MetricRow>
          {canSeeCost ? <UsagePanel projectId={projectId} /> : null}
        </CardContent>
      </Card>
    </section>
  );
}
